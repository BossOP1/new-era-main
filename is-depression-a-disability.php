    <p class="<?= $p_class ?>">
      If your employer has 15 or more employees (or is a state or local government entity), they are required by federal law to provide <strong>reasonable accommodations</strong> to qualified employees with disabilities, provided the accommodations do not cause the company undue hardship.
    </p>

    <p class="<?= $p_class ?>">
      Reasonable accommodations are adjustments to work processes, environments, or schedules that enable an employee with depression to fulfill their essential job duties. Common examples include:
