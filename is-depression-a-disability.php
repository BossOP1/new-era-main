      Having a formal diagnosis of Major Depressive Disorder (MDD), Persistent Depressive Disorder (dysthymia), or Bipolar Depression is the essential starting foundation, but legal eligibility rests on demonstrating how those symptoms functionally impair your daily capabilities.
    </p>

    <!-- Section: The ADA -->
    <h2 class="<?= $h2_class ?>">Is Depression a Disability Under the Americans with Disabilities Act (ADA)?</h2>

    <p class="<?= $p_class ?>">
      Under the <strong>Americans with Disabilities Act (ADA)</strong>, a disability is defined as a physical or mental impairment that substantially limits one or more major life activities. 
    </p>

    <p class="<?= $p_class ?>">
      The ADA Amendments Act of 2008 (ADAA) made it clear that “major life activities” include mental and cognitive operations, such as:
    </p>

    <ul class="mb-6 list-disc space-y-2.5 pl-6 text-[16px] sm:text-[17px] leading-[1.75] text-[#3d464f]">
      <li><strong>Thinking, concentrating, and problem-solving</strong>: Processing complex instructions, prioritizing tasks, or retaining information.</li>
      <li><strong>Sleeping and resting</strong>: Insomnia, broken sleep patterns, or excessive hypersomnia that disrupts normal waking schedules.</li>
      <li><strong>Interacting with others</strong>: Social withdrawal, severe irritability, anxiety, or communication breakdown.</li>
      <li><strong>Caring for oneself</strong>: Basic hygiene, proper nutrition, preparing meals, or maintaining a safe living environment.</li>
      <li><strong>Working</strong>: Attending shifts consistently, meeting reasonable deadlines, and sustaining sustained attention.</li>
    </ul>

    <p class="<?= $p_class ?>">
      Crucially, the law recognizes that depression is often <em>episodic</em>. Under the ADAA, an impairment that is episodic or in remission is still considered a disability if it substantially limits a major life activity when active. This means that if you experience severe depressive episodes alternated with periods of stability, you remain protected under the law during both active flare-ups and baseline periods.
    </p>

