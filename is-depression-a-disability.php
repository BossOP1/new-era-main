      Depression is far more than temporary sadness, grief, or burnout. It is a biological, neurochemical mental health condition that affects brain networks regulating mood, energy, cognition, and executive function. For millions of individuals, depression makes getting out of bed, meeting workplace expectations, maintaining relationships, and managing basic daily obligations overwhelming.
    </p>

    <p class="<?= $p_class ?>">
