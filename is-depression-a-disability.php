    <!-- Section: Social Security Disability -->
    <h2 class="<?= $h2_class ?>">Does Depression Qualify for Social Security Disability Benefits (SSDI &amp; SSI)?</h2>

    <p class="<?= $p_class ?>">
      Yes, but the standard for receiving financial disability payments through the Social Security Administration (SSA) is substantially stricter than workplace ADA protections. To receive Social Security Disability Insurance (SSDI) or Supplemental Security Income (SSI), you must demonstrate that your depression prevents you from engaging in any <strong>Substantial Gainful Activity (SGA)</strong> and is expected to last at least 12 continuous months or result in death.
    </p>

    <p class="<?= $p_class ?>">
      The SSA evaluates depression under <strong>Blue Book Listing 12.04</strong> (Depressive, bipolar and related disorders). To meet this listing, you must satisfy specific medical and functional criteria:
    </p>

    <div class="my-6 rounded-2xl border border-ink/10 bg-[#f7f9fa] p-6 sm:p-8">
      <h3 class="m-0 mb-4 font-sans text-[19px] font-bold text-ink">SSA Listing 12.04 Requirements</h3>
      
      <div class="space-y-4">
        <div>
          <h4 class="m-0 mb-1 text-[16px] font-bold text-brand-blue">Paragraph A (Clinical Symptoms):</h4>
          <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
            Medical documentation of at least five persistent symptoms: depressed mood; diminished interest in almost all activities; appetite disturbance with weight change; sleep disruption; psychomotor agitation or retardation; decreased energy; feelings of guilt or worthlessness; difficulty concentrating or thinking; or thoughts of death/suicide.
          </p>
        </div>

        <div>
          <h4 class="m-0 mb-1 text-[16px] font-bold text-brand-blue">Paragraph B (Functional Limitations):</h4>
          <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
            You must show <strong>extreme limitation in one</strong>, or <strong>marked limitation in two</strong>, of the following functional areas:
          </p>
          <ul class="my-2 list-disc space-y-1 pl-5 text-[14px] text-[#4a5568]">
            <li>Understanding, remembering, or applying information</li>
            <li>Interacting with others (coworkers, supervisors, the public)</li>
            <li>Concentrating, persisting, or maintaining pace</li>
            <li>Adapting or managing oneself (regulating emotions, hygiene, safety)</li>
          </ul>
        </div>

        <div>
          <h4 class="m-0 mb-1 text-[16px] font-bold text-brand-blue">Paragraph C (Serious &amp; Persistent):</h4>
          <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
            Alternatively, if your condition has lasted at least 2 years with ongoing medical treatment and mental health support, and you have marginal capacity to adapt to environmental changes or daily demands.
          </p>
        </div>
      </div>
