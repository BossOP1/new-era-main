    <h2 class="<?= $h2_class ?>">Frequently Asked Questions About Depression and Disability</h2>

    <div class="my-8 space-y-4">
      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">1. Is depression legally considered a disability?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Yes. Under the Americans with Disabilities Act (ADA) and other federal and state laws, major depression can qualify as a disability if it substantially limits one or more major life activities, such as working, sleeping, concentrating, or caring for yourself.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">2. What qualifies depression for ADA workplace protections?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Under the ADA, protection does not require total inability to work. Instead, you qualify if your clinical depression significantly restricts your cognitive, emotional, or physical functioning compared to an average person. The ADA also covers episodic depression during active symptom flare-ups.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">3. What workplace accommodations can I request for depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Common reasonable accommodations include flexible scheduling for therapy or TMS appointments, quiet work environments, modified lighting, written task instructions, intermittent FMLA medical leave, and hybrid or remote work arrangements.
        </p>
