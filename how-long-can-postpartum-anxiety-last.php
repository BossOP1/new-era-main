    <p class="<?= $p_class ?>">
      When symptoms interfere significantly with daily functioning or psychotherapy alone is insufficient, medication can provide vital stabilization. SSRIs (selective serotonin reuptake inhibitors) and SNRIs are commonly prescribed and have extensive safety data for postpartum and breastfeeding parents.
    </p>
    <p class="<?= $p_class ?>">
      A psychiatric clinician will carefully review infant feeding, medical history, and dosage to ensure that any prescribed medication is safe, effective, and well tolerated.
