    </p>

    <p class="<?= $p_class ?>">
      If you are noticing signs of both conditions, learning more about <a href="postpartum.php" class="text-brand-blue underline font-semibold hover:text-brand-blue-dark">postpartum depression</a> and discussing your experiences with a clinician will ensure both conditions are treated concurrently.
    </p>

