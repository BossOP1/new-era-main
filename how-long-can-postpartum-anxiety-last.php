    <h3 class="<?= $h3_class ?>">Ongoing Sleep Deprivation</h3>
    <p class="<?= $p_class ?>">
      Sleep disruption is one of the biggest challenges of early parenthood. Repeated nighttime waking impairs the brain's prefrontal cortex, making it much harder to regulate emotions and dampen the nervous system's threat responses. While broken sleep is expected with an infant, severe or prolonged sleep loss directly fuels anxiety cycles.
    </p>

    <h3 class="<?= $h3_class ?>">Limited Support</h3>
    <p class="<?= $p_class ?>">
      Caring for a newborn alone can feel deeply isolating. Without practical support from a partner, family, or trusted community members, the relentless pressure can quickly become overwhelming.
    </p>

    <h3 class="<?= $h3_class ?>">Previous Anxiety or Depression</h3>
    <p class="<?= $p_class ?>">
      Individuals with a personal or family history of mood or anxiety disorders carry a higher predisposition to postpartum symptoms. Having a prior history does not make postpartum anxiety inevitable, but it provides crucial context for your clinical team.
    </p>

    <h3 class="<?= $h3_class ?>">Ongoing Life Stress</h3>
    <p class="<?= $p_class ?>">
      Financial worries, marital tension, returning to the workplace, health complications, and housing instability amplify anxious feelings. For people experiencing concurrent mood symptoms, understanding the close relationship between <a href="depression.php" class="text-brand-blue underline font-semibold hover:text-brand-blue-dark">depression</a> and <a href="anxiety.php" class="text-brand-blue underline font-semibold hover:text-brand-blue-dark">anxiety</a> helps ensure an accurate clinical diagnosis.
