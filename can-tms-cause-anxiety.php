        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          As TMS reactivates dormant neurological pathways in the prefrontal cortex, the emotional numbness associated with depression lifts. Feeling emotions more acutely can temporarily feel overwhelming or irritable until your nervous system stabilizes.
