      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">3. Can TMS cause panic attacks?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          TMS does not physiologically generate panic attacks. However, individuals prone to claustrophobia or medical anxiety may experience situational panic due to sensory discomfort or feeling nervous in the treatment chair. Clinicians can pause pulses or adjust settings to prevent distress.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">4. Does TMS treat anxiety as well as depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Yes. The FDA cleared TMS for major depressive disorder with comorbid anxiety symptoms in 2020. Protocols targeting the right DLPFC with low-frequency pulses are specifically designed to quiet hyperactive anxiety circuits.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">5. Can I take anti-anxiety medication during TMS therapy?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Most patients continue their current medications during TMS. However, high doses of benzodiazepines (such as Xanax or Ativan) can alter your motor threshold because they dampen cortical excitability. Discuss all prescriptions with your supervising psychiatrist.
        </p>
      </div>

