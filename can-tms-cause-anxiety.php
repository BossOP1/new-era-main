      When beginning any new psychiatric treatment, it is natural to monitor your symptoms closely. If you are considering or have recently started Transcranial Magnetic Stimulation (TMS), you might wonder whether the magnetic pulses can trigger nervous tension, panic, or heightened worry.
    </p>

