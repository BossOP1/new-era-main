            <strong class="text-ink font-bold block">The "TMS Dip"</strong>
            <span>Around weeks two or three (sessions 10 to 15), some patients experience a transient plateau or brief flare-up of symptoms—often termed the "TMS dip." As brain networks rapidly adjust to daily neurostimulation, temporary shifts in mood or nervous tension can occur before sustained improvement sets in.</span>
          </div>
        </li>
        <li class="flex items-start gap-3">
