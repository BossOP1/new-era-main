            <strong class="text-ink font-bold block">Transition Out of Emotional Blunting</strong>
            <span>Severe clinical depression often creates profound emotional numbness. As TMS lifts that fog, patients sometimes feel feelings "more sharply" before their coping systems catch up, which can initially feel like an emotional overload or anxious alertness.</span>
          </div>
        </li>
      </ul>
