    <!-- Section: Does TMS Actually Treat Anxiety? -->
    <h2 class="<?= $h2_class ?>">Does TMS Actually Treat Anxiety?</h2>

    <p class="<?= $p_class ?>">
      Yes. While mild adjustment jitters can occur, the overarching scientific evidence proves that TMS is an exceptionally potent tool for <em>reducing</em> anxiety.
    </p>

    <p class="<?= $p_class ?>">
      In 2020, the U.S. Food and Drug Administration (FDA) cleared TMS for the treatment of <strong>major depressive disorder with comorbid anxiety symptoms (anxious depression)</strong>. Clinical trials showed that patients receiving TMS experienced substantial drops on standardized anxiety rating scales, such as the Hamilton Anxiety Rating Scale (HAM-A) and GAD-7.
    </p>

    <p class="<?= $p_class ?>">
      For patients suffering from obsessive-compulsive fears, TMS is also FDA-cleared for <a href="ocd.php" class="text-brand-blue underline font-semibold hover:text-brand-blue-dark">OCD</a>, specifically targeting hyperactive frontostriatal brain circuits to reduce compulsive rituals and intrusive thoughts.
    </p>

    <!-- Section: Left vs. Right Sided Protocols -->
