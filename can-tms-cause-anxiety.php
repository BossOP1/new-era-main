          <div>
            <strong class="text-ink font-bold block">Sensory and Anticipatory Stress</strong>
            <span>The clicking sound and localized tapping sensation on the scalp can be surprising during initial sessions. Sitting in a clinical chair while adjusting to a novel medical environment can naturally evoke situational anxiety, particularly for people who already struggle with health-related worries.</span>
          </div>
