    <!-- Section: How TMS Interacts With Neural Circuits -->
    <h2 class="<?= $h2_class ?>">How TMS Interacts With Neural Circuits</h2>

    <p class="<?= $p_class ?>">
      TMS uses pulsed magnetic fields to stimulate neurons in specific regions of the brain. In standard protocols for depression, treatment targets the <strong>left dorsolateral prefrontal cortex (DLPFC)</strong>, an area that typically shows decreased metabolic activity in individuals with mood disorders.
    </p>

    <p class="<?= $p_class ?>">
      The DLPFC has direct connections to deeper limbic structures, including the <strong>amygdala</strong>, which processes threat detection, fear, and emotional intensity. As magnetic stimulation awakens dormant pathways and encourages new synaptic connections (neuroplasticity), the communication loop between the prefrontal cortex and the limbic system begins to recalibrate.
    </p>

    <p class="<?= $p_class ?>">
      During the initial stages of this neurological re-engagement, some patients report feeling slightly "energized," emotionally sensitive, or mildly anxious. This is not structural brain damage or the onset of a new disorder; it reflects the brain adapting to renewed electrical and metabolic activity.
    </p>

    <!-- Section: Why Anxiety Might Spike Early -->
    <h2 class="<?= $h2_class ?>">Why Can Anxiety Temporarily Increase Early in Treatment?</h2>

    <p class="<?= $p_class ?>">
      When patients notice increased anxiety early in their TMS journey, several common factors are typically involved:
    </p>

    <div class="mb-8 rounded-[16px] bg-white border border-ink/10 p-6 sm:p-7 shadow-sm">
      <ul class="m-0 space-y-4 p-0 list-none text-[15px] sm:text-[16px] text-[#47525d]">
