        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">1. Can TMS make my anxiety permanently worse?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          No. Clinical research and long-term registry studies show that TMS does not cause permanent or chronic anxiety disorders. Any heightened anxiety reported during early sessions is temporary and typically subsides as the brain adapts to neurostimulation.
