        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">2. What is the TMS dip, and how long does it last?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          The "TMS dip" is a brief period—often occurring between sessions 10 and 15—where patients experience a temporary plateau or mild flare-up of mood and anxiety symptoms. It generally lasts just a few days to a week before symptoms resume improving.
        </p>
