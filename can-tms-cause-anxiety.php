        <div class="rounded-[12px] bg-[#f0f4f7] p-5 border border-brand-blue/20">
          <h3 class="m-0 mb-2 font-bold text-[17px] text-brand-blue">Right-Sided Low-Frequency (1 Hz)</h3>
          <p class="m-0 text-[14px] leading-[1.7] text-ink/75">
            <strong>Inhibitory stimulation:</strong> Calms down hyperactive neural circuits in the right prefrontal cortex that fuel chronic panic, restlessness, racing worries, and physical anxiety.
          </p>
        </div>
      </div>
    </div>

    <p class="<?= $p_class ?>">
      If a patient experiences pronounced anxiety during left-sided stimulation, a skilled psychiatrist can modify the protocol—either by incorporating right-sided inhibitory pulses (bilateral TMS) or adjusting the stimulation intensity—to restore emotional equilibrium.
    </p>

