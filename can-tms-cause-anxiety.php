          <p class="m-0 text-[14px] leading-[1.7] text-ink/75">
            <strong>Excitatory stimulation:</strong> Activates underactive neurons in the left prefrontal cortex to combat depressive lethargy, apathy, brain fog, and sadness.
          </p>
