    <h2 class="<?= $h2_class ?>">Is ADHD a Disability?</h2>

    <p class="<?= $p_class ?>">
      Yes, ADHD can qualify as a disability in certain circumstances. Under the Americans with Disabilities Act (ADA), a disability can include a physical or mental impairment that substantially limits one or more major life activities. Major life activities can include learning, reading, concentrating, thinking, communicating, and working.
    </p>

    <p class="<?= $p_class ?>">
      The ADA does not mean that every person diagnosed with ADHD automatically receives disability protection. Instead, the impact of the condition on the individual is important.
    </p>

    <p class="<?= $p_class ?>">
      For example, a person with ADHD may experience significant difficulty concentrating, organizing tasks, completing work, managing time, or maintaining attention. If these difficulties substantially limit a major life activity, the individual may have protections under applicable disability laws.
    </p>

    <p class="<?= $p_class ?>">
      The legal definition can also differ from how healthcare professionals use the word “disability.” A clinician may focus on diagnosis, symptoms, functioning, and treatment needs, while a government agency, school, employer, or benefits program may apply its own eligibility standards.
    </p>

