    <h2 class="<?= $h2_class ?>">Frequently Asked Questions About Postpartum Depression Prevention</h2>

    <div class="my-8 space-y-4">
      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">1. Can you completely prevent postpartum depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          While no strategy offers a 100% guarantee due to unpredictable hormonal drops and delivery complications, proactive prevention significantly reduces incidence and severity. Mothers who establish protected sleep routines, access prenatal counseling, and build support networks recover faster and experience lower rates of clinical PPD.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">2. When does postpartum depression typically begin?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Postpartum depression can develop at any point during the first year after childbirth. Symptoms commonly emerge between weeks 4 and 12 postpartum, though for some women, symptoms start during pregnancy (perinatal depression) or appear around the time infant breastfeeding is discontinued and hormonal levels shift again.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">3. What is the difference between the baby blues and postpartum depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          The baby blues affect up to 80% of new mothers and consist of mild mood swings, tearfulness, and fatigue that resolve on their own within two weeks. Postpartum depression is a medical condition characterized by persistent despair, numbness, panic, severe insomnia, or detachment that lasts beyond two weeks and impairs daily functioning.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">4. Does sleep deprivation directly cause postpartum depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Yes, chronic sleep fragmentation is a primary biological trigger for maternal depression. Severe sleep deprivation disrupts the brain's prefrontal cortex, impairs emotional regulation, and elevates stress hormones like cortisol. Ensuring mothers receive at least one continuous 4-hour sleep block is essential for neurological recovery.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">5. If I had depression in the past, will I definitely get postpartum depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Having a personal or family history of major depression increases your statistical vulnerability, but it does not mean postpartum depression is inevitable. By alerting your healthcare team early, continuing counseling, and creating a postpartum care plan, many women with depressive histories have healthy postpartum experiences.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">6. Can fathers or partners experience postpartum depression?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Yes. Paternal postpartum depression affects approximately 10% of new fathers and non-gestational partners. Triggers include extreme sleep disruption, acute financial stress, relationship strain, and hormonal shifts. Partners experiencing chronic irritability, withdrawal, or hopelessness should also seek clinical support.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
