    <!-- Section: Prenatal Planning -->
    <h2 class="<?= $h2_class ?>">Proactive Steps to Take During Pregnancy</h2>

    <p class="<?= $p_class ?>">
      The best time to prevent postpartum depression is before your baby arrives. Implementing these foundational strategies during your second and third trimesters sets up a protective buffer:
    </p>

    <div class="my-6 space-y-4">
      <div class="rounded-xl border border-ink/10 bg-white p-5 shadow-sm">
        <h4 class="m-0 mb-1.5 font-sans text-[16px] font-bold text-brand-blue">1. Create a Written Postpartum Mental Health Plan</h4>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Just as you write a birth plan for labor, outline your postpartum mental health expectations with your partner or support person. Detail who will help with household tasks, who will monitor your mood, and which healthcare providers you will contact if sadness or anxiety escalates.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-5 shadow-sm">
        <h4 class="m-0 mb-1.5 font-sans text-[16px] font-bold text-brand-blue">2. Formulate a Protected Sleep Strategy</h4>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Sleep deprivation is not just a symptom of postpartum depression—it is a direct neurological trigger. Aim to structure nighttime feeding shifts so the mother receives at least <strong>one continuous 4-hour block of uninterrupted sleep</strong> each night. Even one solid REM cycle dramatically stabilizes serotonin and dopamine regulation.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-5 shadow-sm">
        <h4 class="m-0 mb-1.5 font-sans text-[16px] font-bold text-brand-blue">3. Engage in Preventive Therapy</h4>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          The U.S. Preventive Services Task Force (USPSTF) strongly recommends cognitive behavioral therapy (CBT) or interpersonal therapy (IPT) during pregnancy for women at increased risk of perinatal depression. Preventive counseling teaches coping mechanisms for role transitions, boundary-setting, and catastrophic thinking.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-5 shadow-sm">
        <h4 class="m-0 mb-1.5 font-sans text-[16px] font-bold text-brand-blue">4. Connect with a Reproductive Psychiatrist Early</h4>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          If you take psychiatric medications or have a past depressive history, schedule a preconception or perinatal psychiatric evaluation. Establishing care with a clinician ahead of time ensures you have immediate access to expert support without facing weeks-long waitlists postpartum.
        </p>
      </div>
    </div>

    <!-- Section: Early Postpartum Protection -->
    <h2 class="<?= $h2_class ?>">Safeguarding Your Mental Health in the Fourth Trimester</h2>

    <p class="<?= $p_class ?>">
      The first 12 weeks after birth—often referred to as the "fourth trimester"—involve the steepest drop in estrogen and progesterone in human physiology. Protect yourself during this window with these evidence-based daily practices:
    </p>

    <ul class="mb-6 list-disc space-y-2.5 pl-6 text-[16px] sm:text-[17px] leading-[1.75] text-[#3d464f]">
      <li><strong>Establish Strict Visitor Boundaries</strong>: Well-meaning visitors can inadvertently increase maternal stress. Limit visits to individuals who actively assist (bringing nourishing meals, running errands, folding laundry) rather than guests who expect to be hosted.</li>
      <li><strong>Prioritize Nutrient-Dense Meals &amp; Hydration</strong>: Postpartum healing, breastfeeding, and hormonal rebalancing demand substantial micronutrients (omega-3 fatty acids, iron, vitamin D, B-vitamins, and magnesium). Nutrient deficiencies impair neurotransmitter synthesis.</li>
      <li><strong>Release Perfectionism &amp; Comparison</strong>: The pressure to "bounce back" or project effortless motherhood on social media fosters intense inadequacy. Focus solely on resting, healing, and bonding with your baby.</li>
      <li><strong>Gentle Daily Sunlight Exposure</strong>: Stepping outside for 10 to 15 minutes of natural morning sunlight resets melatonin rhythms, enhances daytime alertness, and elevates mood naturally.</li>
    </ul>

