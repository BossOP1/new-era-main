    <p class="<?= $p_class ?>">
      Migraines are often misunderstood as simply "bad headaches." In reality, a migraine is a complex neurological disorder involving waves of abnormal electrical and chemical activity across brain networks, vascular inflammation, and heightened sensory sensitivity. 
    </p>

    <p class="<?= $p_class ?>">
      Because the physical headache is only one chapter of a larger physiological cascade, patients frequently experience debilitating symptoms days before the throbbing pain begins and long after it subsides. Learning the progression of each stage—and what factors prolong attacks—can help you intervene earlier, reduce disability, and regain control over your schedule.
    </p>

    <!-- Section: The 4 Phases -->
    <h2 class="<?= $h2_class ?>">The Four Phases of a Migraine Attack</h2>

    <p class="<?= $p_class ?>">
      While not every migraineur experiences all four stages during every episode, recognizing each phase provides vital clues for timing medications and managing sensory input:
    </p>

    <div class="my-6 space-y-4">
      <div class="rounded-xl border border-ink/10 bg-white p-6 shadow-sm">
        <div class="mb-2 flex items-center justify-between">
          <h3 class="m-0 font-sans text-[18px] font-bold text-ink">Phase 1: Prodrome (The Warning Phase)</h3>
          <span class="rounded-full bg-brand-blue/10 px-3 py-0.5 text-[12px] font-bold text-brand-blue">Duration: 24 to 48 Hours</span>
        </div>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Occurring one to two days before head pain starts, the prodrome involves subtle neurochemical signals. Common symptoms include unexplained fatigue, frequent yawning, stiff neck muscles, food cravings (especially for sweets or carbohydrates), mood changes (sudden irritability or euphoria), and heightened sensitivity to light and sound. Recognizing prodrome symptoms allows patients to prepare, hydrate, and avoid potential triggers.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-6 shadow-sm">
        <div class="mb-2 flex items-center justify-between">
          <h3 class="m-0 font-sans text-[18px] font-bold text-ink">Phase 2: Aura (Neurological Disturbances)</h3>
          <span class="rounded-full bg-brand-blue/10 px-3 py-0.5 text-[12px] font-bold text-brand-blue">Duration: 5 to 60 Minutes</span>
        </div>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Experienced by approximately 25% to 30% of individuals with migraines, aura is caused by cortical spreading depression—a slow wave of depolarizing electrical activity across the cerebral cortex. It most commonly manifests as visual disturbances (flashing zigzag lines, blind spots, shimmering lights), but can also involve sensory changes like pins-and-needles tingling in the face or fingers, speech difficulty, or mild dizziness. Aura typically peaks and fades within an hour.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-6 shadow-sm">
        <div class="mb-2 flex items-center justify-between">
          <h3 class="m-0 font-sans text-[18px] font-bold text-ink">Phase 3: Attack / Headache (The Acute Pain Phase)</h3>
          <span class="rounded-full bg-brand-blue/10 px-3 py-0.5 text-[12px] font-bold text-brand-blue">Duration: 4 to 72 Hours</span>
        </div>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          This is the primary pain stage characterized by intense, throbbing, or pulsating pain that is usually concentrated on one side of the head, though it can affect both. Accompanying symptoms include severe photophobia (light sensitivity), phonophobia (sound sensitivity), nausea, vomiting, and worsened discomfort with minimal physical movement. Without effective acute medical treatment, this phase lasts up to 3 days.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-6 shadow-sm">
        <div class="mb-2 flex items-center justify-between">
          <h3 class="m-0 font-sans text-[18px] font-bold text-ink">Phase 4: Postdrome (The "Migraine Hangover")</h3>
          <span class="rounded-full bg-brand-blue/10 px-3 py-0.5 text-[12px] font-bold text-brand-blue">Duration: 24 to 48 Hours</span>
        </div>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Once the throbbing pain recedes, the postdrome begins. Patients frequently describe feeling mentally wiped out, drained, and "hungover." Common postdrome symptoms include brain fog, difficulty concentrating, body aches, scalp tenderness, dizziness, and emotional vulnerability. Cognitive demands and strenuous exertion during this window can trigger a relapse of pain.
        </p>
      </div>
    </div>

    <!-- Section: Episodic vs Chronic -->
    <h2 class="<?= $h2_class ?>">Episodic vs. Chronic Migraines: Understanding the Frequency</h2>

    <p class="<?= $p_class ?>">
      Healthcare providers classify migraine disorders into two primary clinical categories based on how frequently attacks recur:
    </p>

    <div class="my-6 grid gap-4 sm:grid-cols-2">
      <div class="rounded-xl border border-ink/10 bg-white p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-sans text-[17px] font-bold text-ink">Episodic Migraines</h3>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Occur on fewer than 15 days per month. Attacks may strike once or twice a month, or several times a week during stressful periods, with clear symptom-free intervals in between.
        </p>
      </div>

      <div class="rounded-xl border border-ink/10 bg-white p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-sans text-[17px] font-bold text-ink">Chronic Migraines</h3>
        <p class="m-0 text-[15px] leading-[1.7] text-[#4a5568]">
          Defined as experiencing headaches on <strong>15 or more days per month for at least 3 months</strong>, with at least 8 of those days meeting full diagnostic criteria for a migraine attack. Chronic migraine is severely disabling and requires comprehensive preventive management.
        </p>
      </div>
    </div>

    <!-- Section: Status Migrainosus -->
    <h2 class="<?= $h2_class ?>">When a Migraine Won’t Go Away: Status Migrainosus</h2>

    <p class="<?= $p_class ?>">
      In some cases, a migraine headache refuses to break and persists beyond the standard 72-hour window. Clinically, this is termed <strong>status migrainosus</strong>.
    </p>

    <p class="<?= $p_class ?>">
      Status migrainosus is a debilitating medical complication requiring urgent medical evaluation. The relentless pain, ongoing nausea, dehydration from persistent vomiting, and severe sleep deprivation can exhaust the central nervous system. Treatment typically requires physician-administered IV infusion therapies (such as anti-inflammatories, antiemetics, magnesium, or dihydroergotamine) to break the pain cycle.
    </p>

    <!-- Section: Triggers Extending Duration -->
    <h2 class="<?= $h2_class ?>">Factors That Can Make Migraines Last Longer</h2>

    <p class="<?= $p_class ?>">
      If your migraines frequently linger for multiple days, several underlying biological and environmental triggers may be extending their duration:
    </p>

    <ul class="mb-6 list-disc space-y-2.5 pl-6 text-[16px] sm:text-[17px] leading-[1.75] text-[#3d464f]">
      <li><strong>Medication Overuse Headaches (Rebound Effect)</strong>: Taking acute pain medications (NSAIDs, acetaminophen, triptans, or combination analgesics) more than 10 to 15 days per month can sensitize pain pathways, causing rebound headaches that prolong suffering into a chronic daily cycle.</li>
      <li><strong>Hormonal Shifts</strong>: Menstrual migraines triggered by the sudden drop in estrogen right before a woman’s period are clinically proven to be longer-lasting, more severe, and more resistant to standard abortive treatments.</li>
      <li><strong>Chronic Stress &amp; Anxiety</strong>: Prolonged elevation of cortisol and muscle tension keeps the trigeminal nerve system hyper-sensitized, preventing the brain from resetting to its calm baseline.</li>
      <li><strong>Disrupted Sleep Architecture</strong>: Both sleep deprivation and oversleeping (such as sleeping in late on weekends) disrupt circadian rhythms that regulate migraine threshold thresholds.</li>
      <li><strong>Delayed Treatment Intervention</strong>: Waiting hours before taking prescribed acute rescue medications allows central sensitization to take hold, making the attack much more difficult to terminate.</li>
    </ul>

