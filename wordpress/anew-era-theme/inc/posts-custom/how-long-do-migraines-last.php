    <h2 class="<?= $h2_class ?>">Frequently Asked Questions About Migraine Duration</h2>

    <div class="my-8 space-y-4">
      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">1. Can a migraine attack last for an entire week?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Yes. While the intense head pain phase usually lasts between 4 and 72 hours, adding the 1-to-2-day prodrome and the 1-to-2-day postdrome means a single migraine episode can disable a person for up to 7 consecutive days. If the actual headache phase persists beyond 72 hours without relief, it is considered status migrainosus and requires medical attention.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">2. Why does my head still feel foggy and achy after the pain stops?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          This lingering sensation is called the postdrome phase, or "migraine hangover." During an attack, widespread neurochemical shifts, vascular changes, and inflammation occur throughout the brain. Even after the acute pain resolves, it takes 24 to 48 hours for cerebral metabolic balance and neurotransmitter levels to normalize.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">3. How do I know if my migraines are episodic or chronic?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          If you have 14 or fewer headache days per month, your condition is classified as episodic. If you experience headaches on 15 or more days per month for at least three consecutive months—with at least 8 of those days fulfilling migraine criteria—your condition has transitioned to chronic migraine. Keeping a daily headache diary is the most accurate way to track your monthly total.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 bg-white p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">4. What causes a migraine to last longer than usual?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Common factors that prolong migraine duration include waiting too long to take acute abortive medication, severe dehydration, sudden estrogen drops before menstruation, excessive caffeine withdrawal or intake, intense psychological stress, and the development of medication overuse headaches from frequent pain relievers.
        </p>
      </div>

      <div class="rounded-[16px] bg-white border border-ink/10 p-6 shadow-sm">
        <h3 class="m-0 mb-2 font-bold text-[18px] text-ink">5. What is a medication overuse headache (rebound headache)?</h3>
        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Medication overuse headaches occur when acute pain relievers (such as ibuprofen, acetaminophen, triptans, or combination medications containing caffeine) are taken more than 10 to 15 days a month. As the medication wears off, the brain experiences a rebound effect that triggers a fresh headache, creating a vicious cycle of near-daily pain.
        </p>
      </div>

