        <p class="m-0 text-[15px] sm:text-[16px] leading-[1.7] text-[#58616a]">
          Seek immediate emergency medical care if you experience a "thunderclap" headache (reaching peak explosive severity within seconds), head pain accompanied by high fever, stiff neck, confusion, seizure, double vision, numbness, or weakness on one side of the body, or if you experience a severe headache following a head injury.
