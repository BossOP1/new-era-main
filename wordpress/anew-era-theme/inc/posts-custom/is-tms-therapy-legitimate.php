    </p>

    <p class="<?= $p_class ?>">
      In individuals suffering from clinical depression, functional neuroimaging consistently reveals decreased metabolic activity and reduced blood flow in the <strong>left dorsolateral prefrontal cortex (DLPFC)</strong>. By delivering targeted magnetic pulses to this exact region, TMS induces small electrical currents that stimulate dormant neurons, encourage neurotransmitter release (serotonin, dopamine, norepinephrine), and foster long-term neuroplasticity—the brain’s ability to rebuild healthy synaptic connections.
    </p>

    <p class="<?= $p_class ?>">
      Unlike medications that circulate throughout your bloodstream and affect every organ in your body, TMS acts locally on the brain networks that govern mood and emotional processing.
