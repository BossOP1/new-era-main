    <h3 class="<?= $h3_class ?>">Medication Management</h3>
    <p class="<?= $p_class ?>">
      Psychiatric medication may also be recommended. Certain medications—such as selective serotonin reuptake inhibitors (SSRIs)—can help lower the neurological intensity of obsessive thoughts and compulsive urges.
    </p>
    <p class="<?= $p_class ?>">
      Medication decisions should always be made alongside a qualified psychiatric provider who can assess dosage, monitor tolerance, and coordinate medication alongside active psychotherapy.
    </p>

